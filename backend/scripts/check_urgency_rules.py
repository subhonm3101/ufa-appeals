from app.services.priority_features import urgency_level

cases = [
    ("Оголённые провода рядом с детьми", 3),
    ("Открытый колодец без крышки у поликлиники", 3),
    ("После дождя затопило квартиру", 3),
    ("После ремонта дороги асфальт пошёл трещинами", 0),
    ("Листва забила ливнёвку, стоит большая лужа", 0),
    ("На остановке нет навеса и скамейки", 0),
    ("Автобус ходит раз в час, большие очереди", 0),
]

print("Проверка текущих правил срочности:")
for text, expected in cases:
    actual = urgency_level(text)
    status = "OK" if actual == expected else "НЕ СОВПАЛО"
    print(f"[{status}] ожидалось={expected}, получено={actual}: {text}")
