def poisson(lam):
    if lam <= 0:
        return 0
    L = math.exp(-lam)
    k, p = 0, 1.0
    while True:
        p *= rnd.random()
        if p <= L:
            return k
        k += 1


def cap(s):
    return s[:1].upper() + s[1:]


def low(s):
    return s[:1].lower() + s[1:]


def pick_sub(cat, month):
    subs = [(name, v) for name, (months, v) in T[cat].items() if months is None or month in months]
    return rnd.choice(subs)


def fill(variant, place):
    return cap(variant.format(place=place, since=rnd.choice(SINCE)).strip())


def typo(s):
    idx = [i for i, ch in enumerate(s) if ch.isalpha() and i + 1 < len(s) and s[i + 1].isalpha()]
    if len(idx) < 5:
        return s
    i = rnd.choice(idx[2:-2] if len(idx) > 6 else idx)
    op = rnd.choice(["swap", "drop", "dup"])
    if op == "swap":
        return s[:i] + s[i + 1] + s[i] + s[i + 2:]
    if op == "drop":
        return s[:i] + s[i + 1:]
    return s[:i] + s[i] + s[i:]


def noise(s):
    r = rnd.random()
    if r < 0.12:
        s = typo(s)
    r = rnd.random()
    if r < 0.05:
        s = s.lower().rstrip(".")
    elif r < 0.065:
        s = s.upper()
    elif r < 0.115:
        s = s.rstrip(".") + "!!!"
    return s


used_texts = set()


def make_text(cat, sub, variants, place, mixed):
    for _ in range(60):
        core = fill(rnd.choice(variants), place)
        text = rnd.choice(OPENERS) + core
        if mixed:
            cat2 = rnd.choice([c for c in T if c != cat])
            _, v2 = pick_sub(cat2, 6)
            pl2 = rnd.choice(POOLS[cat2])
            second = fill(rnd.choice(v2), pl2)
            text += " " + rnd.choice(CONNECT) + low(second)
        if sub in ("questions", "newstop"):
            text += rnd.choice(["", "", " Спасибо.", " Жду ответа."])
        else:
            text += rnd.choice(CLOSERS)
        text = noise(text)
        if text not in used_texts:
            used_texts.add(text)
            return text
    raise RuntimeError("не удалось получить уникальный текст")


def spike_mult(cat, district, d):
    m = 1.0
    for c, dist, a, b, k in SPIKES:
        if c == cat and dist == district and a <= d <= b:
            m = max(m, k)
    return m


